import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { after, before, describe, it } from 'node:test';
import { api } from './helpers/env.mjs';
import { hardwareStand } from './helpers/hardware-stand.mjs';
import { cleanup, createAdmin, createUser } from './helpers/stand.mjs';
import { closeDatabase, query } from './helpers/db.mjs';

describe('Gravit hardware: real CMS protocol, bans and session isolation', { skip: process.env.HARDWARE_HTTP_TEST !== '1' }, () => {
  let stand, device, auth, otherAuth, secondDevice;
  before(async () => { stand = await hardwareStand(); });
  after(async () => { if (stand) await stand.cleanup(); await cleanup(); await closeDatabase(); });
  const connect = async (session, value, expected = 200) => { const result = await stand.kernel('/hardware/connect', { sessionID: session.session.id, hardware: { id: value.id } }, { expected }); if (expected === 200) session.hardwareId = value.id; return result; };
  const join = (session, username, serverId, expected = 201) => stand.kernel('/joinServer', { username, accessToken: session.minecraftAccessToken, serverId, hardwareId: session.hardwareId }, { expected });
  const lookup = (session, expected) => stand.kernel('/getUserByToken', null, { headers: { Bearer: session.oauthAccessToken }, expected });
  const ban = async (devices, expiresAt) => {
    const result = await stand.root.post('/admin/hardware/ban', { userUuid: stand.uuid, devices: devices.map(({ id, revision }) => ({ id, revision })), reason: 'Hardware moderation contract', expiresAt });
    assert.equal(result.status, 201, JSON.stringify(result.body));
    return result.body;
  };
  it('protects hardware routes and rejects malformed reports', async () => {
    assert.equal((await fetch(`${api}/auth/gravit/hardware/by-key`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 401);
    const admin = await createAdmin(['panel.users.read', 'panel.users.ban']);
    assert.equal((await admin.session.get(`/admin/hardware/users/${stand.uuid}`)).status, 403);
    await stand.kernel('/hardware/create', { info: { ...stand.info, hwDiskId: 'x'.repeat(257) }, publicKey: stand.key() }, { expected: 400 });
    await stand.kernel('/hardware/create', { info: {}, publicKey: stand.key() }, { expected: 400 });
    await stand.kernel('/hardware/by-key', { publicKey: 'not-valid' }, { expected: 400 });
    await stand.kernel('/hardware/by-id', { id: randomUUID() }, { expected: 204 });
  });
  it('deduplicates concurrent reports and preserves all keys through fuzzy recognition', async () => {
    const publicKey = stand.key();
    const devices = await Promise.all(Array.from({ length: 4 }, () => stand.create(stand.info, publicKey)));
    device = devices[0];
    assert.ok(devices.every((row) => row.id === device.id));
    const fuzzy = (await stand.kernel('/hardware/by-data', { info: { ...stand.info, hwDiskId: stand.info.hwDiskId.slice(0, -1) + 'Z' } }, { expected: 200 })).body;
    assert.equal(fuzzy.id, device.id);
    const rotatedKey = stand.key();
    await stand.kernel('/hardware/add-key', { hardware: { id: device.id }, publicKey: rotatedKey }, { expected: 200 });
    for (const key of [publicKey, rotatedKey]) assert.equal((await stand.kernel('/hardware/by-key', { publicKey: key }, { expected: 200 })).body.id, device.id);
  });
  it('binds two accounts to validated launcher sessions and exposes hardware only with its permission', async () => {
    auth = await stand.authorize();
    otherAuth = await stand.authorize(stand.second);
    assert.match(auth.session.id, /^[0-9a-f-]{36}$/);
    await join(auth, stand.player.username, 'missing-hardware', 403);
    await connect(auth, device);
    await connect(otherAuth, device);
    assert.equal((await lookup(auth, 200)).body.id, auth.session.id);
    assert.equal((await lookup(auth, 200)).body.userHardware.id, device.id);
    const rows = await stand.rows();
    assert.equal(rows[0].users.length, 2);
    assert.equal(rows[0].info.hwDiskId, stand.info.hwDiskId);
    const me = await stand.player.session.get('/auth/me');
    assert.ok(!JSON.stringify(me.body).includes(stand.info.hwDiskId));
    await stand.kernel('/hardware/connect', { sessionID: randomUUID(), hardware: { id: device.id } }, { expected: 401 });
    await join(auth, stand.second.username, 'wrong-owner', 403);
    await join(auth, stand.player.username, 'before-device-ban');
    await stand.kernel('/checkServer', { username: stand.player.username, serverId: 'before-device-ban' }, { expected: 201 });
  });
  it('denies existing OAuth, refresh and game entry after a device ban while website access stays open', async () => {
    await ban(await stand.rows());
    await lookup(auth, 403);
    await lookup(otherAuth, 403);
    await stand.kernel('/refreshToken', { refreshToken: auth.oauthRefreshToken }, { expected: 403 });
    await join(auth, stand.player.username, 'blocked', 403);
    await stand.kernel('/checkServer', { username: stand.player.username, serverId: 'before-device-ban' }, { expected: 403 });
    assert.equal((await stand.player.session.get('/auth/me')).status, 200);
    assert.equal((await query('SELECT COUNT(*) AS count FROM unicore_bans WHERE user_uuid=?', [stand.uuid]))[0].count, 0);
    const fresh = await stand.authorize(stand.second);
    await connect(fresh, device, 403);
    await lookup(fresh, 403);
  });
  it('keeps an allowed device separate from the same player’s banned device and checks the joined session', async () => {
    const serial = randomBytes(20).toString('hex');
    secondDevice = await stand.create({ ...stand.info, hwDiskId: serial, baseboardSerialNumber: serial, displayId: randomBytes(128).toString('base64'), totalMemory: 16 * 1073741824, processorMaxFreq: 3_100_000_000, logicalProcessors: 6, physicalProcessors: 3 });
    assert.notEqual(secondDevice.id, device.id);
    const allowed = await stand.authorize();
    await connect(allowed, secondDevice);
    await stand.kernel('/joinServer', { username: stand.player.username, accessToken: allowed.minecraftAccessToken, serverId: 'restored-different-device', hardwareId: device.id }, { expected: 403 });
    await join(allowed, stand.player.username, 'allowed-device');
    await stand.kernel('/checkServer', { username: stand.player.username, serverId: 'allowed-device' }, { expected: 201 });
    await lookup(auth, 403);
    assert.equal((await lookup(allowed, 200)).body.accessToken, allowed.minecraftAccessToken);
    await stand.kernel('/hardware/connect', { sessionID: allowed.session.id, hardware: { id: device.id } }, { expected: 409 });
  });
  it('removes only the exact ban, keeps history, and expires temporary bans without a cron dependency', async () => {
    let row = (await stand.rows()).find((row) => row.id === device.id);
    const firstBanId = row.activeBan.id;
    const revoke = { banId: firstBanId, revision: row.revision, reason: 'Reviewed hardware appeal' };
    assert.equal((await stand.root.post(`/admin/hardware/${device.id}/revoke`, revoke)).status, 201);
    await lookup(auth, 200);
    row = (await stand.rows()).find((row) => row.id === device.id);
    await ban([row], new Date(Date.now() + 1600).toISOString());
    await lookup(auth, 403);
    assert.equal((await stand.root.post(`/admin/hardware/${device.id}/revoke`, revoke)).status, 201);
    await lookup(auth, 403);
    await new Promise((resolve) => setTimeout(resolve, 1900));
    await lookup(auth, 200);
    row = (await stand.rows()).find((row) => row.id === device.id);
    assert.equal(row.activeBan, null);
    assert.ok(row.history.some((ban) => ban.status === 'EXPIRED'));
    assert.ok(row.history.some((ban) => ban.status === 'REVOKED'));
  });
  it('bans all selected known devices atomically, enforces rights and leaves new devices unblocked', async () => {
    const viewer = await createAdmin(['panel.users.read', 'panel.users.hardware.read']);
    assert.equal((await viewer.session.get(`/admin/hardware/users/${stand.uuid}`)).status, 200);
    const devices = await stand.rows();
    assert.equal((await viewer.session.post('/admin/hardware/ban', { userUuid: stand.uuid, devices: devices.map(({ id, revision }) => ({ id, revision })), reason: 'Denied' })).status, 403);
    const stale = devices.map((row) => ({ ...row })); stale[1].revision++;
    assert.equal((await stand.root.post('/admin/hardware/ban', { userUuid: stand.uuid, devices: stale.map(({ id, revision }) => ({ id, revision })), reason: 'Atomic stale selection' })).status, 409);
    assert.ok((await stand.rows()).every((row) => !row.activeBan));
    await ban(devices);
    assert.ok((await stand.rows()).every((row) => row.activeBan));
    const fresh = await stand.create({ ...stand.info, hwDiskId: randomBytes(30).toString('hex'), baseboardSerialNumber: randomBytes(30).toString('hex'), displayId: randomBytes(128).toString('base64'), totalMemory: 8 * 1073741824, processorMaxFreq: 2_700_000_000, logicalProcessors: 4, physicalProcessors: 2 });
    assert.equal(fresh.banned, false);
  });
  it('keeps legacy mode available and rejects revoked launcher sessions', async () => {
    const legacy = await stand.authorize(stand.second, false);
    await join(legacy, stand.second.username, 'legacy-compatible');
    await stand.kernel('/checkServer', { username: stand.second.username, serverId: 'legacy-compatible' }, { expected: 201 });
    await stand.kernel('/deleteSession', { user: { username: stand.second.username } }, { expected: 201 });
    await lookup(legacy, 401);
    await join(legacy, stand.second.username, 'revoked-session', 401);
    await stand.kernel('/checkServer', { username: stand.second.username, serverId: 'legacy-compatible' }, { expected: 401 });
  });
  it('applies hierarchy to every account sharing a device and records successful moderation without serials', async () => {
    const high = await createUser({ superuser: true });
    const serial = randomBytes(35).toString('hex');
    const item = await stand.create({ ...stand.info, hwDiskId: serial, baseboardSerialNumber: serial, displayId: randomBytes(128).toString('base64'), totalMemory: 256 * 1073741824, processorMaxFreq: 6_700_000_000, logicalProcessors: 128, physicalProcessors: 64 });
    const first = await stand.authorize(), second = await stand.authorize(high);
    await connect(first, item); await connect(second, item);
    const mod = await createAdmin(['panel.users.read', 'panel.users.hardware.read', 'panel.users.hardware.ban', 'panel.users.hardware.revoke']);
    const row = (await stand.rows()).find((row) => row.id === item.id);
    const request = { userUuid: stand.uuid, devices: [{ id: item.id, revision: row.revision }], reason: 'Hierarchy must protect every linked account' };
    assert.equal((await mod.session.post('/admin/hardware/ban', request)).status, 403);
    assert.equal((await stand.rows()).find((row) => row.id === item.id).activeBan, null);
    const ids = [...stand.deviceIds];
    const records = await query(`SELECT action, meta FROM unicore_audit_logs WHERE target_type='hardware' AND action IN ('hardware.ban','hardware.revoke') AND target_id IN (${ids.map(() => '?').join(',')})`, ids);
    assert.ok(records.some((record) => record.action === 'hardware.ban'));
    assert.ok(records.some((record) => record.action === 'hardware.revoke'));
    assert.ok(records.every((record) => !JSON.stringify(record.meta).includes(stand.info.hwDiskId)));
  });
});
